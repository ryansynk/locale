"""Move the pre-split indexes/ and results/ trees to the label layout.

Applies benchmark/rename_map.json (generated by make_rename_map.py from the
naming oracle -- never edit it by hand): every old directory is renamed to
its new path, every artifact directory gets the config.json the new code
checks on load, results and hits parquets get the dataset/encoder/index/
search columns in place of ``model``, and the sweep symlink is re-pointed.
Nothing is deleted: only renames, in-place parquet rewrites and the removal
of directories left empty by a move. Idempotent -- an entry whose old path
is gone and whose new path is in place is skipped, so a crashed run is
resumed by running it again.

    uv run python scripts/migrate_layout.py --dry-run     # print every move
    uv run python scripts/migrate_layout.py               # do it
"""

import argparse
import json
import os
import shutil
import sys
from pathlib import Path

import polars as pl

BENCH = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(BENCH))
from src.config import CONFIG_FILE, DONE_FILE, check_config, read_config, write_config  # noqa: E402

LABEL_COLUMNS = ("dataset", "encoder", "index", "search")
# run_benchmark._annotate_results' column order, for rewritten parquets
COLUMN_ORDER = [
    "query_id", "results", "hits", "index_size_gb", "avg_time", "dataset", "encoder", "index",
    "search", "mutation_rate", "query_type", "checkpoint", "max_len", "checkpoint_step_num", "chunk_type",
]


class Migrator:
    def __init__(self, root: Path, dry_run: bool):
        self.root = root
        self.dry_run = dry_run
        self.moves = 0
        self.rewrites = 0
        self.skipped = 0
        self.notes: list[str] = []

    # ------------------------------------------------------------ primitives
    def _p(self, rel: str) -> Path:
        return self.root / rel

    def say(self, msg: str) -> None:
        print(("[dry-run] " if self.dry_run else "") + msg)

    def move(self, src: Path, dst: Path) -> None:
        self.say(f"mv {src.relative_to(self.root)} -> {dst.relative_to(self.root)}")
        self.moves += 1
        if self.dry_run:
            return
        dst.parent.mkdir(parents=True, exist_ok=True)
        if dst.exists() or dst.is_symlink():
            raise FileExistsError(f"refusing to overwrite {dst}")
        os.rename(src, dst)

    def rmdir_empty_up_to(self, d: Path, stop: Path) -> None:
        """Remove d and its parents while they are empty, never past stop."""
        while d != stop and d.is_relative_to(stop):
            if not d.is_dir() or d.is_symlink() or any(d.iterdir()):
                return
            self.say(f"rmdir {d.relative_to(self.root)} (empty)")
            if not self.dry_run:
                d.rmdir()
            d = d.parent

    def stamp(self, d: Path, identity: dict, done: bool | None = None) -> None:
        on_disk = read_config(d) if d.is_dir() else None
        if on_disk is not None:
            check_config(d, identity)  # raises on a mismatch
        else:
            self.say(f"write {d.relative_to(self.root)}/{CONFIG_FILE}")
            if not self.dry_run:
                write_config(d, identity)
        if done and not (d / DONE_FILE).exists():
            self.say(f"touch {d.relative_to(self.root)}/{DONE_FILE}")
            if not self.dry_run:
                (d / DONE_FILE).touch()

    def rewrite_parquet(self, path: Path, labels: dict, dataset: str, probe: Path | None = None) -> None:
        """model column -> dataset/encoder/index/search columns, in place.
        ``probe`` is where the file still sits in a dry run."""
        if not path.exists():
            if not (self.dry_run and probe is not None and probe.exists()):
                return
            schema = pl.read_parquet_schema(probe)
        else:
            schema = pl.read_parquet_schema(path)
        if "model" not in schema and all(c in schema for c in LABEL_COLUMNS):
            return  # already rewritten
        self.say(f"rewrite columns {path.relative_to(self.root)}")
        self.rewrites += 1
        if self.dry_run:
            return
        df = pl.read_parquet(path)
        if "model" in df.columns:
            df = df.drop("model")
        df = df.with_columns(
            pl.lit(dataset).alias("dataset"),
            pl.lit(labels["encoder"], dtype=pl.String).alias("encoder"),
            pl.lit(labels["index"], dtype=pl.String).alias("index"),
            pl.lit(labels["search"], dtype=pl.String).alias("search"),
        )
        order = [c for c in COLUMN_ORDER if c in df.columns] + [c for c in df.columns if c not in COLUMN_ORDER]
        tmp = path.with_name(path.name + ".migrating")
        df.select(order).write_parquet(tmp)
        os.replace(tmp, path)

    # --------------------------------------------------------------- indexes
    def migrate_indexes(self, entries: list[dict]) -> None:
        # Encoder dirs, metagraph/mmseqs and the symlink first: engine entries
        # inside an encoder dir are located relative to its NEW path.
        for e in entries:
            if e["kind"] == "encoder":
                self._migrate_dir(e)
            elif e["kind"] == "index":
                self._migrate_dir(e)
            elif e["kind"] == "symlink":
                self._migrate_symlink(e)
        for e in entries:
            if e["kind"] == "engine":
                self._migrate_engine_dir(e)
            elif e["kind"] == "engine_files":
                self._migrate_engine_files(e)
            elif e["kind"] == "leftover_files":
                self.notes.append(f"left in place under {e['old']}: {e['files']} ({e['note']})")
        for e in entries:
            for d in e.get("leftover_dirs", []):
                self.notes.append(f"stale directory kept: {e['new']}/{d} (interrupted-run partials; delete by hand)")

    def _migrate_dir(self, e: dict) -> None:
        old, new = self._p(e["old"]), self._p(e["new"])
        dataset_root = self._p(e["old"]).parents[len(Path(e["old"]).parts) - 3]  # indexes/<ds>
        if old == new:
            pass
        elif new.is_relative_to(old):
            raise RuntimeError(f"{e['old']} -> {e['new']}: new path inside old")
        elif old.is_relative_to(new):
            # metagraph/k31 -> metagraph, llmed/<tag> -> llmed: hoist through
            # a sibling name, since a directory cannot be renamed onto its
            # own parent.
            tmp = new.with_name(new.name + ".migrating")
            if old.is_dir() and not old.is_symlink():
                self.move(old, tmp)
                self.rmdir_empty_up_to(old.parent, dataset_root)
                if self.dry_run:
                    self.say(f"mv {tmp.relative_to(self.root)} -> {new.relative_to(self.root)}")
            if tmp.exists():
                if new.exists() and not any(new.iterdir()):
                    self.say(f"rmdir {new.relative_to(self.root)} (empty)")
                    if not self.dry_run:
                        new.rmdir()
                self.move(tmp, new)
            elif old.is_dir() and self.dry_run:
                pass
            elif new.is_dir() and ((new / DONE_FILE).exists() or (new / CONFIG_FILE).exists()):
                self.skipped += 1  # hoisted by an earlier run
            else:
                raise FileNotFoundError(f"neither {old} nor a migrated {new}")
        elif old.is_dir() and not old.is_symlink():
            self.move(old, new)
            self.rmdir_empty_up_to(old.parent, dataset_root)
        elif new.is_dir():
            self.skipped += 1
        else:
            raise FileNotFoundError(f"neither {old} nor {new}")
        if not self.dry_run or new.is_dir():
            self.stamp(new, e["config"], e.get("done"))
        else:
            self.say(f"write {e['new']}/{CONFIG_FILE}")

    def _migrate_symlink(self, e: dict) -> None:
        old, new = self._p(e["old"]), self._p(e["new"])
        dataset_root = new.parent
        if old.is_symlink():
            self.say(f"rm symlink {e['old']}; ln -s {e['target']} {e['new']}")
            self.moves += 1
            if not self.dry_run:
                old.unlink()
                if new.exists() or new.is_symlink():
                    raise FileExistsError(f"refusing to overwrite {new}")
                new.symlink_to(e["target"])
            self.rmdir_empty_up_to(old.parent, dataset_root)
        elif new.is_symlink():
            self.skipped += 1
        else:
            raise FileNotFoundError(f"neither symlink {old} nor {new}")

    def _engine_src(self, e: dict) -> Path | None:
        """Where the engine artifact sits now: under the moved encoder dir,
        or still under the old one (dry run before any move)."""
        for cand in (self._p(e["encoder_new"]) / e["old_rel"], self._p(e["old"])):
            if cand.exists():
                return cand
        return None

    def _migrate_engine_dir(self, e: dict) -> None:
        new = self._p(e["new"])
        src = self._engine_src(e)
        if src is not None and src != new:
            self.move(src, new)
            self.rmdir_empty_up_to(src.parent, self._p(e["encoder_new"]))
        elif new.is_dir():
            self.skipped += 1
        else:
            raise FileNotFoundError(f"no engine artifact for {e['new']}")
        if not self.dry_run or new.is_dir():
            self.stamp(new, e["config"], e.get("done"))
        else:
            self.say(f"write {e['new']}/{CONFIG_FILE}" + (f"; touch {e['new']}/{DONE_FILE}" if e.get("done") else ""))

    def _migrate_engine_files(self, e: dict) -> None:
        new = self._p(e["new"])
        src_dir = self._engine_src(e)
        moved_any = False
        for f in e["files"]:
            if src_dir is not None and (src_dir / f).exists():
                self.move(src_dir / f, new / f)
                moved_any = True
            elif not (new / f).exists():
                raise FileNotFoundError(f"{f} missing from both {src_dir} and {new}")
        if not moved_any:
            self.skipped += 1
        if src_dir is not None:
            self.rmdir_empty_up_to(src_dir, self._p(e["encoder_new"]))
        if not self.dry_run or new.is_dir():
            self.stamp(new, e["config"], e.get("done"))
        else:
            self.say(f"write {e['new']}/{CONFIG_FILE}" + (f"; touch {e['new']}/{DONE_FILE}" if e.get("done") else ""))

    # --------------------------------------------------------------- results
    def migrate_results(self, entries: list[dict]) -> None:
        for e in entries:
            old, new = self._p(e["old"]), self._p(e["new"])
            results_root = old.parent
            moved_any = False
            for old_name, new_name in e["files"].items():
                if (old / old_name).exists():
                    self.move(old / old_name, new / new_name)
                    moved_any = True
                elif not (new / new_name).exists():
                    raise FileNotFoundError(f"{old / old_name} missing and {new / new_name} absent")
                self.rewrite_parquet(new / new_name, e["labels"], e["dataset"], probe=old / old_name)
            if not moved_any:
                self.skipped += 1
            if old.is_dir():
                self.rmdir_empty_up_to(old, results_root)
            if not self.dry_run or new.is_dir():
                self.stamp(new, e["config"])
            else:
                self.say(f"write {e['new']}/{CONFIG_FILE}")

    def migrate_hits(self, entries: list[dict]) -> None:
        for e in entries:
            old, new = self._p(e["old"]), self._p(e["new"])
            hits_root = old.parents[1]  # results/<ds>_topk_hits
            if old.exists():
                self.move(old, new)
                self.rmdir_empty_up_to(old.parent, hits_root.parent)
            elif new.exists():
                self.skipped += 1
            else:
                raise FileNotFoundError(f"{old} missing and {new} absent")
            self.rewrite_parquet(new, e["labels"], e["dataset"], probe=old)
            search_dir = self._p(e["search_dir"])
            if not self.dry_run or search_dir.is_dir():
                self.stamp(search_dir, e["config"])
            else:
                self.say(f"write {e['search_dir']}/{CONFIG_FILE}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--map", default=str(BENCH / "rename_map.json"))
    ap.add_argument("--root", default=str(BENCH), help="directory holding indexes/ and results/")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()
    rename_map = json.loads(Path(args.map).read_text())
    m = Migrator(Path(args.root).resolve(), args.dry_run)
    print(f"== indexes ({len(rename_map['indexes'])} entries)")
    m.migrate_indexes(rename_map["indexes"])
    print(f"== results ({len(rename_map['results'])} directories)")
    m.migrate_results(rename_map["results"])
    print(f"== hits ({len(rename_map['hits'])} files)")
    m.migrate_hits(rename_map["hits"])
    for root in sorted({Path(e["old"]).parents[1] for e in rename_map["hits"]}):
        d = m.root / root
        if d.is_dir() and not any(d.iterdir()):
            m.say(f"rmdir {root} (empty)")
            if not m.dry_run:
                d.rmdir()
    print(f"== done: {m.moves} moves, {m.rewrites} parquet rewrites, {m.skipped} entries already migrated")
    for n in m.notes:
        print("note:", n)
    for a in rename_map.get("results_archive", []):
        print(f"note: {a} is not in the map (archived; old layout)")


if __name__ == "__main__":
    main()
